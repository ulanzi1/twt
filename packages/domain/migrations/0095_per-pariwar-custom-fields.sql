-- The per-Pariwar, per-host-entity, APPEND-ONLY VERSIONED registry of tenant-authored custom-field
-- definitions. Mirrors 0084's routing-policy half (versioned-immutable rows + composite self-FK +
-- append-only trigger) and 0088's CHECK-mirror doctrine.
--
-- ⚠ DO NOT REGENERATE with `db:generate` (the discipline from 0021 onward): the drizzle snapshot
-- baseline is frozen at 0020_snapshot.json, so a regenerate diffs CURRENT schema against 0020, wrongly
-- re-emits applied migrations and can raise 42P07. HAND-AUTHORED, carrying ONLY this story's DDL. No
-- snapshot emitted.
--
-- ⚠ DO NOT EDIT THIS FILE ONCE APPLIED. drizzle-kit skips an already-applied migration by journal
-- `when` (NOT by SQL hash), so an in-place edit silently never runs — the change would exist in the
-- file and nowhere else, which is worse than not making it. Add a new migration instead.
--
-- The roles (twt_app / twt_service) already exist from migration 0002 — no CREATE ROLE.
--
-- Hand-supplements (relative to what drizzle would emit):
--   1. GRANT SELECT, INSERT, UPDATE to twt_app. NOT DELETE — retirement is a VERSION (a new row with
--      retired_at set), never a row removal. A deleted definition makes every value stored under it
--      uninterpretable, which is data loss dressed as tidying.
--   2. ENABLE + FORCE ROW LEVEL SECURITY (FORCE applies even to the non-superuser table owner).
--   3. The three tenant-isolation policies, from policies/pariwar-custom-field-definitions-rls.ts.
--   4. The append-only BEFORE UPDATE trigger (0084 hand-supplement #4 is the template): the SOLE
--      legitimately-mutable column on an existing row is superseded_by_version.
--   5. The composite self-FK on the forward-pointer. ⚠ It references the FULL TUPLE
--      (pariwar_id, host_entity, field_key, superseded_by_version) → (…, version). A bare
--      version→version reference would not even be creatable: `version` alone is NOT unique here, and
--      the only unique key is the four-column pin below.
--   6. ⭐ THE FROZEN-GOVERNANCE CHECK — layer 2 of AC3. See its own comment block.
--
-- ⚠ NOTE WHAT IS ABSENT: no `current_state` write-rejection trigger and no state-invariant gate. This
-- is NOT a sixth event-derived-state primitive (the 10.8 Decision-3 split): nothing outside the admin
-- write path ever moves a definition — an admin publishes a version, and the version IS the record.

CREATE TABLE "pariwar_custom_field_definitions" (
	"id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
	"pariwar_id" uuid NOT NULL,
	"host_entity" text NOT NULL,
	"field_key" text NOT NULL,
	"version" integer NOT NULL,
	"definition" jsonb NOT NULL,
	"effective_at" timestamp with time zone NOT NULL,
	"retired_at" timestamp with time zone,
	"authored_by_actor" uuid,
	"actor_display" text,
	"audit_id" uuid,
	"superseded_by_version" integer,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL
);
