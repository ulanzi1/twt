// Story 14.3 (migration 0208; decision `2026-11-20-467` DL4, DL5, DL8) — the personal data breach register.
//
// TWO GLOBAL tables (no `pariwar_id` — the Trust is the Data Fiduciary):
//   · `breach_incidents`        — one row per incident, written once at open; never updated.
//   · `breach_incident_entries` — the incident's append-only timeline; everything else about an incident (its status, the
//                                 Board report's due time, what has been recorded) is DERIVED from these, never stored.
// Both are APPEND-ONLY for every role (0208's triggers refuse UPDATE / DELETE / TRUNCATE), RLS is enabled and forced with
// ZERO policies, the member-facing role `twt_app` has no grant at all, and `twt_service` holds SELECT + INSERT only.
// No member PII column: affected people are a count, data categories and Pariwar ids inside an entry's payload.
//
// This file is pg-free (drizzle column builders only): the two closed lists below are the SOURCE the migration's CHECKs,
// the contracts mirror and the regression spec are held equal to.

import { sql } from 'drizzle-orm';
import { bigint, boolean, check, index, jsonb, pgTable, text, timestamp, uuid } from 'drizzle-orm/pg-core';

/**
 * The closed list of entry kinds (DL5, widened to FIFTEEN by decision `2026-11-20-471` — `board_extension_withdrawn`). LOCKSTEP: the
 * `breach_incident_entries_kind_check` (0208, re-created by 0209); contracts `BreachEntryKind`.
 */
export const BREACH_ENTRY_KINDS = [
  'assessment',
  'timeline_event',
  'mitigation',
  'cause_findings',
  'remedial',
  'principals_notice_recorded',
  'board_initial_recorded',
  'board_report_recorded',
  'board_extension_recorded',
  'board_extension_withdrawn',
  'cert_in_report_recorded',
  'owner_review',
  'signoff_recorded',
  'closed',
  'note',
] as const;
export type BreachEntryKind = (typeof BREACH_ENTRY_KINDS)[number];

/** The closed list of detection sources (DL8). LOCKSTEP: 0208's `breach_incidents_detection_source_check`; contracts. */
export const BREACH_DETECTION_SOURCES = [
  'audit_chain_break',
  'pii_scrape_failure',
  'validity_cache_alert',
  'cross_tenant_read_anomaly',
  'pii_export_volume',
  'rls_bypass_attempt',
  'out_of_hours_privileged_session',
  'class_a_dead_letter',
  'external_report',
  'other',
] as const;
export type BreachDetectionSource = (typeof BREACH_DETECTION_SOURCES)[number];

/** Bounds the CHECKs carry (0208). */
export const BREACH_INCIDENT_TITLE_MAX = 200;
export const BREACH_DETECTION_SIGNAL_REF_MAX = 200;

export const breachIncidents = pgTable(
  'breach_incidents',
  {
    /** Generated by the handler BEFORE the audit intent (the audit locator embeds it); the default is a backstop. */
    incidentId: uuid('incident_id').defaultRandom().primaryKey(),
    /** Set at open, never changed (the table is append-only). A rehearsal and a real incident never share a row. */
    isRehearsal: boolean('is_rehearsal').notNull(),
    title: text('title').notNull(),
    /** When the Trust became aware — the start of the Board's 72-hour clock (DPDP Rules 2025 Rule 7(2)(b)). */
    becameAwareAt: timestamp('became_aware_at', { withTimezone: true, mode: 'date' }).notNull(),
    openedAt: timestamp('opened_at', { withTimezone: true, mode: 'date' }).notNull().defaultNow(),
    detectionSource: text('detection_source').$type<BreachDetectionSource>().notNull(),
    /** e.g. an `audit_integrity_checks.check_id` — a reference, not a foreign key. */
    detectionSignalRef: text('detection_signal_ref'),
    /** The admin user id. No FK — the record outlives the account (0188's rationale). */
    openedBy: uuid('opened_by').notNull(),
    /** The admin's display name, SNAPSHOT at open (a later rename never rewrites it). */
    openedByDisplay: text('opened_by_display').notNull(),
    /** The compensating-audit intent line this row was written under. */
    auditId: uuid('audit_id').notNull(),
  },
  (t) => [
    check('breach_incidents_title_check', sql`char_length(btrim(${t.title})) BETWEEN 1 AND 200`),
    check('breach_incidents_aware_before_opened_check', sql`${t.becameAwareAt} <= ${t.openedAt}`),
    check(
      'breach_incidents_detection_source_check',
      sql`${t.detectionSource} IN ('audit_chain_break', 'pii_scrape_failure', 'validity_cache_alert', 'cross_tenant_read_anomaly', 'pii_export_volume', 'rls_bypass_attempt', 'out_of_hours_privileged_session', 'class_a_dead_letter', 'external_report', 'other')`,
    ),
    check(
      'breach_incidents_detection_signal_ref_check',
      sql`${t.detectionSignalRef} IS NULL OR char_length(btrim(${t.detectionSignalRef})) BETWEEN 1 AND 200`,
    ),
    check('breach_incidents_display_check', sql`char_length(btrim(${t.openedByDisplay})) >= 1`),
  ],
);
export type BreachIncidentRow = typeof breachIncidents.$inferSelect;

export const breachIncidentEntries = pgTable(
  'breach_incident_entries',
  {
    /** Generated by the handler BEFORE the audit intent. No default — the one writer always supplies it. */
    entryId: uuid('entry_id').primaryKey(),
    /** GENERATED ALWAYS AS IDENTITY — the order of an incident's entries, everywhere. Appends are serialised per incident. */
    entrySeq: bigint('entry_seq', { mode: 'bigint' }).generatedAlwaysAsIdentity().notNull(),
    incidentId: uuid('incident_id')
      .notNull()
      .references(() => breachIncidents.incidentId),
    kind: text('kind').$type<BreachEntryKind>().notNull(),
    /** One strict shape per kind (contracts). Free text is typed by staff — refer to members by id, never by name. */
    payload: jsonb('payload').$type<Record<string, unknown>>().notNull(),
    /** The DB's clock at insert — a trigger overwrites any written value (never `now()`, which is the transaction's start). */
    recordedAt: timestamp('recorded_at', { withTimezone: true, mode: 'date' }).notNull().default(sql`clock_timestamp()`),
    recordedBy: uuid('recorded_by').notNull(),
    recordedByDisplay: text('recorded_by_display').notNull(),
    auditId: uuid('audit_id').notNull(),
  },
  (t) => [
    index('breach_incident_entries_incident_seq_idx').on(t.incidentId, t.entrySeq),
    check(
      'breach_incident_entries_kind_check',
      sql`${t.kind} IN ('assessment', 'timeline_event', 'mitigation', 'cause_findings', 'remedial', 'principals_notice_recorded', 'board_initial_recorded', 'board_report_recorded', 'board_extension_recorded', 'cert_in_report_recorded', 'owner_review', 'signoff_recorded', 'closed', 'note')`,
    ),
    check('breach_incident_entries_payload_object_check', sql`jsonb_typeof(${t.payload}) = 'object'`),
    check('breach_incident_entries_display_check', sql`char_length(btrim(${t.recordedByDisplay})) >= 1`),
  ],
);
export type BreachIncidentEntryRow = typeof breachIncidentEntries.$inferSelect;
