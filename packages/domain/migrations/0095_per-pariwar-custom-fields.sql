-- ─────────────────────────────────────────────────────────────────────────────────────────────────
-- ⭐ (6) LAYER 2 OF THE GOVERNANCE FENCE (Story 10.12 AC3) — the DB mirror.
--
-- Migration 0088's doctrine, verbatim: "an app-layer rule with no DB mirror is a rule that holds only
-- for the callers who happen to go through the app layer."
--
-- The app-layer fence (packages/domain/src/custom-fields/frozen-governance.ts) is richer than this:
-- it carries thirteen pattern families and normalizes `-`, `.` and whitespace to `_` before matching.
-- This CHECK deliberately does NOT try to reproduce all of that — a CHECK deep enough to encode the
-- whole denylist would be a rule engine in DDL, and one that drifted from the TS would be worse than
-- none. What it MUST cover, and does, is the `payout_destination*` family: the FR-100 non-add
-- artifact (architecture §1.13 Hook 2), the one epics.md:3605 names by example, and the one whose
-- absence would be a forward-compat breach rather than an untidy field name.
--
-- The normalization is applied inside the constraint (lower + translate) so `Payout-Destinations` and
-- `payout.destination` are caught here too, not only in TS. A fence a tenant steps over by changing a
-- hyphen is decoration.
--
-- ⚠ WHY THE EPIC'S OWN CITATION COULD NOT DO THIS JOB. epics.md:3605 says a `payout_destinations`
-- field "is rejected by Story 1.16c CI gate". Story 1.16c is `schema-diff`, an invariant scan of
-- COMMITTED REPO STATE — migrations, route literals, Zod exports. A custom field is a key inside a
-- JSONB payload authored at runtime into a database row; `pnpm schema:check` would pass, green and
-- useless, while a Pariwar admin created the field. This constraint, plus the runtime fence, plus
-- `scripts/custom-field-governance/`, are what that citation assumed already existed.
ALTER TABLE "pariwar_custom_field_definitions"
  ADD CONSTRAINT "pariwar_custom_field_definitions_frozen_key_ck"
  CHECK (
    translate(lower("field_key"), '-. ', '___') NOT LIKE 'payout\_destination%'
    AND translate(lower("definition" ->> 'field_key'), '-. ', '___') NOT LIKE 'payout\_destination%'
  );--> statement-breakpoint

-- (7a) Versions start at 1. Unlike feature_flag_versions (whose CHECK is `>= 2`, because a code
-- constant owns version 1 there), custom fields have NO code-resident default: a Pariwar with zero
-- rows simply has no custom fields (story D2). So 1 is the real first version and 0/negative is
-- meaningless.
ALTER TABLE "pariwar_custom_field_definitions"
  ADD CONSTRAINT "pariwar_custom_field_definitions_version_min_ck" CHECK ("version" >= 1);--> statement-breakpoint

-- (7b) The supersession forward-pointer must point FORWARD. Kills the self-reference and
-- backward-reference cases that the FK alone permits (the FK only proves the target EXISTS).
ALTER TABLE "pariwar_custom_field_definitions"
  ADD CONSTRAINT "pariwar_custom_field_definitions_superseded_forward_ck"
  CHECK ("superseded_by_version" IS NULL OR "superseded_by_version" > "version");--> statement-breakpoint

-- (7c) v1 hosts custom fields on MEMBERS ONLY. FR-54, epics.md:108 and §1.7 all name member, claim
-- AND pool — narrowing to one host is a real coverage gap, recorded as a GATED deferral (story D7),
-- not silently absorbed. Claims are additionally guarded by §1.9/§1.13 against exactly this vector.
-- Extending to another host is a one-line ALTER on this constraint plus that host's own fence review.
ALTER TABLE "pariwar_custom_field_definitions"
  ADD CONSTRAINT "pariwar_custom_field_definitions_host_entity_ck"
  CHECK ("host_entity" IN ('member'));--> statement-breakpoint

-- (7d) `definition` must at least be an object carrying the identity + label + type + tier keys the
-- readers dereference, with `definition ->> 'field_key'` agreeing with the COLUMN. The column and the
-- body disagreeing would break the version pin outright: the pin is on the column, every reader keys
-- on the body, and nothing else would notice. Per-field interior validation stays an app-layer
-- concern (`validateCustomFieldDefinition`) — a CHECK deep enough for that would be a rule engine.
ALTER TABLE "pariwar_custom_field_definitions"
  ADD CONSTRAINT "pariwar_custom_field_definitions_definition_shape_ck"
  CHECK (
    jsonb_typeof("definition") = 'object'
    AND "definition" ->> 'field_key' = "field_key"
    AND jsonb_typeof("definition" -> 'label_en') = 'string'
    AND jsonb_typeof("definition" -> 'label_hi') = 'string'
    AND btrim("definition" ->> 'label_en') <> ''
    AND btrim("definition" ->> 'label_hi') <> ''
    AND jsonb_typeof("definition" -> 'field_type') = 'string'
    AND jsonb_typeof("definition" -> 'pii_tier') = 'number'
  );--> statement-breakpoint

-- (7e) v1 accepts pii_tier 3 ONLY (AC4). The app layer raises a typed
-- CustomFieldPiiTierUnsupportedError naming the deferral; this is the mirror for any writer that
-- never reaches it. ⚠ This is a DEFERRAL, not a judgement: Tier-1 needs per-value envelope encryption
-- and Tier-2 needs a blind-index host column, and a shared JSONB column on the certified PII-free
-- `members` table can host neither. When that substrate lands, this constraint widens with it.
-- ⭐ [Review][Patch] A `CASE` guard, not a bare cast: Postgres does NOT guarantee AND/OR short-circuit
-- evaluation order (only CASE does), so `jsonb_typeof(...) = 'number' AND (...)::int = 3` is not a safe
-- way to avoid this. Without the guard, a direct/bypassing INSERT (exactly this CHECK's threat model —
-- a caller that skips the app-layer validator) supplying a non-numeric `pii_tier` (a string, bool,
-- array, or null) risks an opaque `invalid input syntax for type integer` runtime error instead of a
-- clean, named constraint violation. ⚠ `::numeric`, not `::int`: `..._definition_shape_ck` (above)
-- already proves `pii_tier` is a JSON NUMBER, but a JSON number is not necessarily a clean INTEGER
-- literal — `3.5` is a valid JSON number that `'3.5'::int` still raises the same opaque cast error on.
-- `::numeric` accepts any JSON number text (including decimals) and simply compares unequal to 3.
ALTER TABLE "pariwar_custom_field_definitions"
  ADD CONSTRAINT "pariwar_custom_field_definitions_pii_tier_ck"
  CHECK (
    CASE
      WHEN jsonb_typeof("definition" -> 'pii_tier') = 'number' THEN ("definition" ->> 'pii_tier')::numeric = 3
      ELSE false
    END
  );--> statement-breakpoint

