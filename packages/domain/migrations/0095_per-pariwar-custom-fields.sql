-- (4) The append-only trigger — the clause_versions / routing-policy immutability posture. A version
-- row is INSERT-only; the SOLE legitimately-mutable column on an existing row is
-- superseded_by_version (the forward-pointer). Any other column changing on an UPDATE is rejected.
--
-- ⚠ THIS TRIGGER ENUMERATES ITS COLUMNS EXPLICITLY. A column added to this table LATER is OUTSIDE the
-- append-only guarantee until it is added here too — the same footgun 0089 hit on
-- feature_flag_versions.actor_display. If you ALTER TABLE … ADD COLUMN, come back here.
CREATE FUNCTION pariwar_custom_field_definitions_reject_mutation()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.pariwar_id IS DISTINCT FROM OLD.pariwar_id
     OR NEW.host_entity IS DISTINCT FROM OLD.host_entity
     OR NEW.field_key IS DISTINCT FROM OLD.field_key
     OR NEW.version IS DISTINCT FROM OLD.version
     OR NEW.definition IS DISTINCT FROM OLD.definition
     OR NEW.effective_at IS DISTINCT FROM OLD.effective_at
     OR NEW.retired_at IS DISTINCT FROM OLD.retired_at
     OR NEW.authored_by_actor IS DISTINCT FROM OLD.authored_by_actor
     OR NEW.actor_display IS DISTINCT FROM OLD.actor_display
     OR NEW.audit_id IS DISTINCT FROM OLD.audit_id
     OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
    RAISE EXCEPTION
      'pariwar_custom_field_definitions immutable-column write rejected — only superseded_by_version may be updated on an existing version row (Story 10.12 AC1, the clause_versions posture); attempted a change to pariwar_id/host_entity/field_key/version/definition/effective_at/retired_at/authored_by_actor/actor_display/audit_id/created_at on field "%" version % for pariwar %',
      OLD.field_key, OLD.version, OLD.pariwar_id
      USING ERRCODE = 'P0001';
  END IF;
  RETURN NEW;
END;
$$;
--> statement-breakpoint
CREATE TRIGGER pariwar_custom_field_definitions_immutability_guard
  BEFORE UPDATE ON pariwar_custom_field_definitions
  FOR EACH ROW EXECUTE FUNCTION pariwar_custom_field_definitions_reject_mutation();
